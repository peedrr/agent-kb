func TestComputeSHA256(t *testing.T) {
	dir := t.TempDir()
	content := []byte("hello, world")
	f, err := os.CreateTemp(dir, "sha256test")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := f.Write(content); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}

	expected := sha256.Sum256(content)
	expectedHex := hex.EncodeToString(expected[:])

	got, err := ComputeSHA256(f.Name())
	if err != nil {
		t.Fatalf("ComputeSHA256: %v", err)
	}

	if got != expectedHex {
		t.Errorf("ComputeSHA256 = %q, want %q", got, expectedHex)
	}
}

func TestWriteManifest_AtomicWrite(t *testing.T) {
	dir := t.TempDir()
	m := NewManager(dir)

	entries := []Entry{
		{Filename: "data.csv", SHA256: "abc123", LastUpdated: "2026-04-20T10:00:00Z"},
	}

	if err := m.WriteManifest(entries); err != nil {
		t.Fatalf("WriteManifest: %v", err)
	}

	// Verify no temp files remain
	rawDir := filepath.Join(dir, "raw")
	entriesDir, err := os.ReadDir(rawDir)
	if err != nil {
		t.Fatal(err)
	}

	for _, e := range entriesDir {
		if strings.HasPrefix(e.Name(), "files.log.") {
			t.Errorf("temp file left behind: %s", e.Name())
		}
	}
}

func minInt(a, b int) int {
	if a < b {
		return a
	}
	return b
}
