func TestReadManifest_WithEntries(t *testing.T) {
	dir := t.TempDir()
	rawDir := filepath.Join(dir, "raw")
	if err := os.MkdirAll(rawDir, 0750); err != nil {
		t.Fatal(err)
	}

	content := "# Auto-generated by agent-kb. Do not edit manually.\n# filename | sha256 | last_updated\ndata.csv | abc123 | 2026-04-20T10:00:00Z\nimages/logo.png | def456 | 2026-04-20T11:00:00Z\n"
	if err := os.WriteFile(filepath.Join(rawDir, "files.log"), []byte(content), 0600); err != nil {
		t.Fatal(err)
	}

	m := NewManager(dir)
	entries, err := m.ReadManifest()
	if err != nil {
		t.Fatalf("ReadManifest: %v", err)
	}

	if len(entries) != 2 {
		t.Fatalf("expected 2 entries, got %d", len(entries))
	}

	if entries[0].Filename != "data.csv" {
		t.Errorf("entry[0].Filename = %q, want %q", entries[0].Filename, "data.csv")
	}
	if entries[0].SHA256 != "abc123" {
		t.Errorf("entry[0].SHA256 = %q, want %q", entries[0].SHA256, "abc123")
	}
	if entries[0].LastUpdated != "2026-04-20T10:00:00Z" {
		t.Errorf("entry[0].LastUpdated = %q, want %q", entries[0].LastUpdated, "2026-04-20T10:00:00Z")
	}

	if entries[1].Filename != "images/logo.png" {
		t.Errorf("entry[1].Filename = %q, want %q", entries[1].Filename, "images/logo.png")
	}
}

