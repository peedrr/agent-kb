func TestWriteManifest(t *testing.T) {
	dir := t.TempDir()
	m := NewManager(dir)

	entries := []Entry{
		{Filename: "data.csv", SHA256: "abc123", LastUpdated: "2026-04-20T10:00:00Z"},
		{Filename: "images/logo.png", SHA256: "def456", LastUpdated: "2026-04-20T11:00:00Z"},
	}

	if err := m.WriteManifest(entries); err != nil {
		t.Fatalf("WriteManifest: %v", err)
	}

	readBack, err := m.ReadManifest()
	if err != nil {
		t.Fatalf("ReadManifest after write: %v", err)
	}

	if len(readBack) != 2 {
		t.Fatalf("expected 2 entries, got %d", len(readBack))
	}

	if readBack[0].Filename != "data.csv" {
		t.Errorf("entry[0].Filename = %q, want %q", readBack[0].Filename, "data.csv")
	}
	if readBack[1].Filename != "images/logo.png" {
		t.Errorf("entry[1].Filename = %q, want %q", readBack[1].Filename, "images/logo.png")
	}

	data, err := os.ReadFile(m.manifestPath()) //nolint:gosec // test reading known temp file
	if err != nil {
		t.Fatal(err)
	}
	header := "# Auto-generated by agent-kb. Do not edit manually.\n# filename | sha256 | last_updated\n"
	if !strings.HasPrefix(string(data), header) {
		t.Errorf("manifest should start with header, got:\n%s", string(data)[:minInt(len(data), len(header))])
	}
}

